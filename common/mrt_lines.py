def stations_between(start: str, end: str) -> list[str] | None:
    """回傳同一條捷運線上 start、end 兩站之間（含頭尾）的所有站名，不分先後順序。

    如果兩站不在同一條已收錄的線上（或站名不存在），回傳 None。
    有些站名同時存在於多條線（例如轉乘站），只要有任一條線同時包含這兩站即可。
    """
    for stations in ALL_LINES.values():
        if start in stations and end in stations:
            i, j = stations.index(start), stations.index(end)
            lo, hi = min(i, j), max(i, j)
            return stations[lo : hi + 1]
    return None
